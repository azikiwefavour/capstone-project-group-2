import { test, expect } from '@playwright/test'
import { mountFacilitiesFixture } from './facilityHarness.mjs'

for (const viewport of [{ width: 1280, height: 720 }, { width: 1440, height: 900 }, { width: 375, height: 667 }, { width: 390, height: 844 }, { width: 430, height: 932 }, { width: 390, height: 320 }]) {
  test(`per-facility details, dismissal and layout preservation at ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
    await mountFacilitiesFixture(page)
    const content = page.getByRole('region', { name: 'Facilities content', exact: true })
    const table = page.getByRole('table')
    await expect(table.locator('tbody tr')).toHaveCount(7)
    const shape = () => content.evaluate(node => ({ height: node.clientHeight, scrollHeight: node.scrollHeight, footerHeight: node.querySelector('.facilities-pagination').getBoundingClientRect().height, rows: [...node.querySelectorAll('tbody tr')].map(row => row.getBoundingClientRect().height) }))
    const before = await shape()
    const emails = []
    for (const [name, status, dateLabel, amount, close] of [
      ['Preview Hospital 08', 'In trial', 'Trial ends', '₦0 (Free trial)', 'x'],
      ['Preview Hospital 09', 'Past due', 'Subscription expired', '₦840,000', 'outside'],
      ['Preview Hospital 10', 'Active', 'Next renewal', '₦70,000', 'escape'],
    ]) {
      const row = table.getByRole('row', { name: `Details for ${name}`, exact: true })
      await row.scrollIntoViewIfNeeded()
      const totals = await Promise.all([3, 4, 5].map(index => row.getByRole('cell').nth(index).innerText()))
      const position = await content.evaluate(node => ({ top: node.scrollTop, left: node.scrollLeft, page: window.scrollY }))
      await row.getByRole('cell').nth(1).click()
      const dialog = page.getByRole('dialog', { name, exact: true })
      await expect(dialog).toBeVisible()
      await expect(dialog).not.toContainText('Sample facility details')
      await expect(dialog).not.toContainText('Bars are visual placeholders')
      await expect(page.getByRole('status')).toContainText('no active login or facility data')
      const summary = dialog.getByRole('group', { name: 'Facility summary' })
      await expect(summary.getByRole('region')).toHaveCount(3)
      for (const card of await summary.getByRole('region').all()) {
        await expect(card).toHaveCSS('background-color', 'rgb(255, 255, 255)')
        await expect(card).toHaveCSS('border-top-width', '0px')
      }
      if (viewport.width >= 640) {
        const bounds = await dialog.boundingBox()
        expect(bounds.width).toBeLessThanOrEqual(520)
        expect(bounds.height).toBeLessThan(420)
        const nameBounds = await dialog.locator('[data-facility-admin-name]').boundingBox()
        const emailBounds = await dialog.locator('[data-facility-admin-email]').boundingBox()
        expect(Math.abs(nameBounds.y - emailBounds.y)).toBeLessThan(2)
        await expect(dialog.locator('dl > div').first()).toContainText('•')
      }
      await expect(dialog.getByRole('heading', { name, exact: true })).toBeVisible()
      await expect(dialog.getByRole('button', { name: 'Close facility details' })).toBeFocused()
      for (const [index, label] of ['Clinicians', 'Patients', 'Messages (Oct)'].entries()) await expect(dialog.getByRole('region', { name: label, exact: true }).getByText(totals[index], { exact: true })).toBeVisible()
      await expect(dialog.locator('dt', { hasText: dateLabel })).toHaveCount(1)
      await expect(dialog.getByText(status, { exact: true })).toBeVisible()
      await expect(dialog.locator('dl > div').filter({ hasText: 'Subscription Value' }).locator('dd')).toContainText(amount)
      const admin = dialog.locator('dl > div').first()
      emails.push(await admin.locator('[data-facility-admin-email]').innerText())
      if (status === 'In trial') await expect(dialog.getByText('Not available', { exact: true })).toHaveCount(1)
      if (status === 'Past due') await expect(dialog.getByText('Past due', { exact: true })).toHaveCSS('color', 'rgb(184, 63, 92)')
      await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
      await page.keyboard.press('Tab')
      await expect(dialog.getByRole('button', { name: 'Close facility details' })).toBeFocused()
      await page.keyboard.press('Shift+Tab')
      await expect(dialog.getByRole('button', { name: 'Close facility details' })).toBeFocused()
      await dialog.locator('dl > div').last().scrollIntoViewIfNeeded()
      await expect(dialog.getByText(status, { exact: true })).toBeInViewport()
      await page.screenshot({ path: testInfo.outputPath(`details-${status}-${viewport.width}.png`) })
      if (close === 'x') await dialog.getByRole('button', { name: 'Close facility details' }).click()
      else if (close === 'outside') await page.mouse.click(4, 4)
      else await page.keyboard.press('Escape')
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(row).toBeFocused()
      expect(await content.evaluate(node => ({ top: node.scrollTop, left: node.scrollLeft, page: window.scrollY }))).toEqual(position)
    }
    expect(new Set(emails).size).toBe(3)
    const first = table.locator('tbody tr').first()
    await first.getByRole('cell').nth(0).scrollIntoViewIfNeeded()
    const box = await first.getByRole('checkbox').boundingBox()
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
    await first.getByRole('cell').nth(0).click({ position: { x: 2, y: 2 } })
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const eye = first.getByRole('button', { name: 'View Preview Hospital 08', exact: true })
    await eye.click()
    await expect(page.getByRole('dialog', { name: 'Preview Hospital 08', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(eye).toBeFocused()
    await first.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(first).toBeFocused()
    await page.keyboard.press('Space')
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    expect(await shape()).toEqual(before)
    if (viewport.width >= 1280) expect(before.scrollHeight).toBe(before.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
    expect(requests).toEqual([])
  })
}
