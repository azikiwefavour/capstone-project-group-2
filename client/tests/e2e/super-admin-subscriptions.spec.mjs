import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 375, height: 667 }, { width: 390, height: 844 }, { width: 414, height: 896 }, { width: 430, height: 932 }, { width: 1024, height: 768 }, { width: 1280, height: 720 }, { width: 1366, height: 768 }, { width: 1440, height: 900 }]) {
  test(`Subscriptions plan cards and billing cycle at ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
    await page.goto('/super-admin/preview/overview')
    const nav = page.getByRole('navigation', { name: 'Super Admin navigation' })
    await nav.getByRole('link', { name: 'Subscriptions', exact: true }).click()
    await expect(page).toHaveURL(/\/super-admin\/preview\/subscriptions$/)
    await expect(nav.getByRole('link', { name: 'Subscriptions', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(nav.getByRole('link', { name: 'Subscriptions', exact: true })).toHaveCSS('color', 'rgb(71, 90, 162)')
    await expect(page.getByRole('heading', { name: 'Subscriptions', exact: true })).toBeVisible()
    await expect(page.getByRole('status')).toContainText('subscription plan configuration only')
    const monthly = page.getByRole('radio', { name: 'Monthly', exact: true }), annually = page.getByRole('radio', { name: 'Annually', exact: true })
    await expect(monthly).toBeChecked()
    const starter = page.getByRole('article', { name: 'Starter Plan', exact: true }), growth = page.getByRole('article', { name: 'Growth Plan', exact: true })
    await expect(page.getByRole('article')).toHaveCount(2)
    const panel = page.getByRole('region', { name: 'Subscription plans', exact: true })
    await expect(panel.getByRole('radiogroup', { name: 'Billing cycle' })).toHaveCount(1)
    await expect(panel.getByRole('article')).toHaveCount(2)
    await expect(panel).toHaveCSS('background-color', 'rgb(243, 237, 248)')
    for (const card of [starter, growth]) {
      await expect(card).toHaveCSS('background-color', 'rgb(255, 255, 255)')
      const footer = card.locator('[data-plan-subscribers]')
      await expect(footer.getByText('Subscribers', { exact: true })).toBeVisible()
      const bounds = await footer.boundingBox()
      const label = await footer.locator('span').first().boundingBox()
      const count = await footer.locator('span').last().boundingBox()
      expect(Math.abs(label.x - bounds.x)).toBeLessThan(1)
      expect(Math.abs(count.x + count.width - bounds.x - bounds.width)).toBeLessThan(1)
      expect(label.y).toBe(count.y)
    }
    const panelBounds = await panel.boundingBox(), switchBounds = await panel.getByRole('radiogroup').boundingBox(), firstCardBounds = await starter.boundingBox()
    expect(switchBounds.y).toBeGreaterThan(panelBounds.y)
    expect(switchBounds.x).toBeGreaterThan(panelBounds.x)
    expect(switchBounds.y + switchBounds.height).toBeLessThan(firstCardBounds.y)

    await expect(starter.getByText('₦30,000', { exact: true })).toBeVisible()
    await expect(growth.getByText('₦70,000', { exact: true })).toBeVisible()
    await expect(starter.getByText('/month', { exact: true })).toBeVisible()
    await expect(starter.locator('del')).toHaveCount(0)
    const starterFeatures = ['3 clinicians', 'Up to 300 patients', '300 messages/month', 'Audit log and role-based access']
    const growthFeatures = ['Unlimited clinicians', 'Unlimited patients', 'Unlimited messages', 'Audit log and role-based access']
    await expect(starter.getByRole('listitem')).toHaveText(starterFeatures)
    await expect(growth.getByRole('listitem')).toHaveText(growthFeatures)
    await expect(starter.locator('[data-plan-subscribers]').getByText('—', { exact: true })).toBeVisible()
    await expect(growth.locator('[data-plan-subscribers]').getByText('—', { exact: true })).toBeVisible()
    const monthlyBounds = await Promise.all([starter.boundingBox(), growth.boundingBox()])
    if (viewport.width >= 768) {
      expect(monthlyBounds[0].y).toEqual(monthlyBounds[1].y)
      expect(monthlyBounds[1].x).toBeGreaterThan(monthlyBounds[0].x + monthlyBounds[0].width)
      expect(monthlyBounds[0].height).toEqual(monthlyBounds[1].height)
    } else expect(monthlyBounds[1].y).toBeGreaterThan(monthlyBounds[0].y + monthlyBounds[0].height)
    await page.getByRole('radiogroup', { name: 'Billing cycle' }).getByText('Annually', { exact: true }).click()
    await expect(annually).toBeChecked()
    await expect(starter.getByText('₦300,000', { exact: true })).toBeVisible()
    await expect(growth.getByText('₦700,000', { exact: true })).toBeVisible()
    await expect(starter.getByText('/year', { exact: true })).toBeVisible()
    await expect(growth.getByText('/year', { exact: true })).toBeVisible()
    await expect(starter.locator('del')).toHaveText('₦360,000')
    await expect(growth.locator('del')).toHaveText('₦840,000')
    await expect(starter.locator('del')).toHaveCSS('text-decoration-line', 'line-through')
    await expect(starter.getByRole('listitem')).toHaveText(starterFeatures)
    await expect(growth.getByRole('listitem')).toHaveText(growthFeatures)
    await expect(starter.locator('[data-plan-subscribers]').getByText('—', { exact: true })).toBeVisible()
    await expect(growth.locator('[data-plan-subscribers]').getByText('—', { exact: true })).toBeVisible()
    const annualBounds = await Promise.all([starter.boundingBox(), growth.boundingBox()])
    expect(annualBounds.map(bounds => bounds.height)).toEqual(monthlyBounds.map(bounds => bounds.height))
    await page.screenshot({ path: testInfo.outputPath(`subscriptions-annual-${viewport.width}.png`), fullPage: true })
    await page.getByRole('radiogroup', { name: 'Billing cycle' }).getByText('Monthly', { exact: true }).click()
    await expect(monthly).toBeChecked()
    await expect(starter.getByText('₦30,000', { exact: true })).toBeVisible()
    await expect(growth.getByText('₦70,000', { exact: true })).toBeVisible()
    await expect(page.locator('del')).toHaveCount(0)
    await monthly.focus()
    await page.keyboard.press('ArrowRight')
    await expect(annually).toBeChecked()
    await page.keyboard.press('ArrowLeft')
    await expect(monthly).toBeChecked()
    const content = page.getByRole('region', { name: 'Subscriptions content', exact: true })
    if (viewport.width >= 1024) await expect(content).toHaveCSS('overflow-y', 'auto')
    if (viewport.width >= 1280 && viewport.height >= 720) {
      expect(await content.evaluate(node => node.scrollHeight <= node.clientHeight)).toBe(true)
      await expect(page.getByRole('region', { name: 'Subscribers', exact: true }).locator('tbody tr').last()).toBeInViewport()
      await expect(page.getByRole('navigation', { name: 'Subscribers pagination' })).toBeInViewport()
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByRole('region', { name: 'Subscribers', exact: true }).getByRole('table')).toHaveCount(1)
    await expect(content.getByRole('button', { name: /purchase|upgrade|delete|edit/i })).toHaveCount(0)
    await page.reload()
    await expect(monthly).toBeChecked()
    await nav.getByRole('link', { name: 'Facilities', exact: true }).click()
    await expect(page.getByText('No facilities available yet.', { exact: true })).toBeVisible()
    await nav.getByRole('link', { name: 'Overview', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Platform overview', exact: true })).toBeVisible()
    expect(errors).toEqual([])
    expect(requests).toEqual([])
  })
}


test('short desktop keeps every subscriber row accessible without clipping', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 400 })
  await page.goto('/super-admin/preview/subscriptions')
  const content = page.getByRole('region', { name: 'Subscriptions content', exact: true })
  const table = page.getByRole('region', { name: 'Subscribers', exact: true }).getByRole('table')
  await expect(table.getByText('No subscriptions available yet.', { exact: true })).toBeVisible()
  expect(await content.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true)
  await table.locator('tbody tr').last().scrollIntoViewIfNeeded()
  await expect(table.locator('tbody tr').last()).toBeInViewport()
  await page.getByRole('navigation', { name: 'Subscribers pagination' }).scrollIntoViewIfNeeded()
  await expect(page.getByRole('navigation', { name: 'Subscribers pagination' })).toBeInViewport()
})
