import { test, expect } from '@playwright/test'
import { mountFacilitiesFixture } from './facilityHarness.mjs'

for (const viewport of [{ width: 375, height: 667 }, { width: 390, height: 844 }, { width: 414, height: 896 }, { width: 430, height: 932 }, { width: 1024, height: 768 }, { width: 1280, height: 720 }, { width: 1280, height: 800 }, { width: 1366, height: 768 }, { width: 1440, height: 900 }]) {
  test(`Facilities unavailable state and preserved layout at ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors = [], requests = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
    await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
    await page.goto('/super-admin/preview/overview')
    const nav = page.getByRole('navigation', { name: 'Super Admin navigation' })
    await nav.getByRole('link', { name: 'Facilities', exact: true }).click()
    await expect(page).toHaveURL(/\/super-admin\/preview\/facilities$/)
    await expect(nav.getByRole('link', { name: 'Facilities', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('heading', { name: 'Facilities', exact: true })).toBeVisible()
    await expect(page.getByText('Every hospital and clinic on MedTrail. You see accounts, usage and billing, never patient records.', { exact: true })).toBeVisible()
    await expect(page.getByRole('status')).toContainText('no active login or facility data')
    const filters = page.getByRole('group', { name: 'Facility status filters' })
    await expect(filters.getByRole('button')).toHaveText(['All—', 'Active—', 'Trial—', 'Past due—'])
    for (const button of await filters.getByRole('button').all()) await expect(button).toBeEnabled()
    const search = page.getByRole('searchbox', { name: 'Search hospitals by name' })
    await expect(search).toBeEnabled()
    const table = page.getByRole('table')
    await expect(table.getByRole('columnheader')).toHaveCount(8)
    await expect(table.getByRole('columnheader').filter({ has: page.getByRole('button') })).toHaveText(['Facility', 'Plan', 'Clinicians', 'Patients', 'Messages', 'Status'])
    await expect(table.getByText('No facilities available yet.', { exact: true })).toBeVisible()
    await expect(table.getByRole('checkbox')).toHaveCount(1)
    await expect(table.getByRole('checkbox')).toBeDisabled()
    await expect(table.getByRole('button', { name: /^View / })).toHaveCount(0)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    for (const value of ['Active', 'Trial', 'Past due']) {
      await filters.getByRole('button', { name: new RegExp(`^${value}`) }).click()
      await expect(table.getByText('No matching facilities found.', { exact: true })).toBeVisible()
    }
    await filters.getByRole('button', { name: /^All/ }).click()
    await search.fill('unknown')
    await expect(table.getByText('No matching facilities found.', { exact: true })).toBeVisible()
    await search.fill('')
    await expect(table.getByText('No facilities available yet.', { exact: true })).toBeVisible()
    for (const label of ['Facility', 'Plan', 'Clinicians', 'Patients', 'Messages', 'Status']) await table.getByRole('button', { name: `Sort by ${label}`, exact: true }).click()
    const pagination = page.getByRole('navigation', { name: 'Facilities pagination' })
    await expect(pagination.getByRole('button')).toHaveCount(2)
    for (const button of await pagination.getByRole('button').all()) await expect(button).toBeDisabled()
    await expect(page.getByText('Page 1 of 1', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Rows per page: 7, fixed' })).toHaveText('7 / page')
    await expect(page.getByRole('region', { name: 'Facilities content', exact: true })).not.toContainText(/Preview Hospital|admin\d+@|₦|Page 2 of 16/)
    const content = page.getByRole('region', { name: 'Facilities content', exact: true })
    if (viewport.width >= 1280) {
      expect(await content.evaluate(n => n.scrollHeight <= n.clientHeight)).toBe(true)
      const gap = await content.evaluate(n => n.getBoundingClientRect().bottom - n.querySelector('[aria-label="Facilities table and pagination"]').getBoundingClientRect().bottom - parseFloat(getComputedStyle(n).paddingBottom))
      expect(Math.abs(gap)).toBeLessThan(1)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`facilities-unavailable-${viewport.width}.png`), fullPage: true })
    await nav.getByRole('link', { name: 'Subscriptions', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Subscribers', exact: true })).toBeVisible()
    await expect(page.getByText('No subscriptions available yet.', { exact: true })).toBeVisible()
    expect(errors).toEqual([]); expect(requests).toEqual([])
  })
}

test('isolated supplied facility data supports name-only search, status combinations, sorting and pagination', async ({ page }) => {
  const host = await mountFacilitiesFixture(page, { size: 25 })
  const table = host.getByRole('table'), rows = table.locator('tbody tr'), search = host.getByRole('searchbox'), filters = host.getByRole('group', { name: 'Facility status filters' }), nav = host.getByRole('navigation', { name: 'Facilities pagination' })
  await expect(rows).toHaveCount(7)
  await expect(host.getByText('Page 1 of 4', { exact: true })).toBeVisible()
  await nav.getByRole('button', { name: 'Next page' }).click()
  await expect(rows.first()).toContainText('Preview Hospital 08')
  await search.fill('  hOsPiTaL 01 ')
  await expect(rows).toHaveCount(1)
  await expect(rows.first()).toContainText('Preview Hospital 01')
  await expect(host.getByText('Page 1 of 1', { exact: true })).toBeVisible()
  await filters.getByRole('button', { name: /^Trial/ }).click()
  await expect(table.getByText('No matching facilities found.', { exact: true })).toBeVisible()
  await filters.getByRole('button', { name: /^Active/ }).click()
  await expect(rows.first()).toContainText('Preview Hospital 01')
  await search.fill('')
  await expect(rows).toHaveCount(7)
  await filters.getByRole('button', { name: /^All/ }).click()
  for (const query of ['Card Payment', 'Starter Plan', 'admin1@']) {
    await search.fill(query)
    await expect(table.getByText('No matching facilities found.', { exact: true })).toBeVisible()
  }
  await search.fill('')
  for (const [label, index] of [['Facility', 1], ['Plan', 2], ['Clinicians', 3], ['Patients', 4], ['Messages', 5], ['Status', 6]]) {
    await nav.getByRole('button', { name: 'Next page' }).click()
    await table.getByRole('button', { name: `Sort by ${label}`, exact: true }).click()
    await expect(host.getByText('Page 1 of 4', { exact: true })).toBeVisible()
    await expect(table.locator('thead th').nth(index)).toHaveAttribute('aria-sort', 'ascending')
    await table.getByRole('button', { name: `Sort by ${label}`, exact: true }).click()
    await expect(table.locator('thead th').nth(index)).toHaveAttribute('aria-sort', 'descending')
  }
  for (let i = 0; i < 3; i++) await nav.getByRole('button', { name: 'Next page' }).click()
  await expect(rows).toHaveCount(4)
  await expect(nav.getByRole('button', { name: 'Next page' })).toBeDisabled()
  await nav.getByRole('button', { name: 'Previous page' }).click()
  await expect(rows).toHaveCount(7)
})

test('facility states preserve unknown totals and close a modal if its record disappears', async ({ page }) => {
  const host = await mountFacilitiesFixture(page)
  await host.getByRole('button', { name: 'View Preview Hospital 08', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.evaluate(() => window.renderFacilitiesFixture('unavailable', []))
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(host.getByText('No facilities available yet.', { exact: true })).toBeVisible()
  await page.evaluate(() => window.renderFacilitiesFixture('loading', []))
  await expect(host.getByText('Loading facilities...', { exact: true })).toBeVisible()
  await page.evaluate(() => window.renderFacilitiesFixture('error', []))
  await expect(host.getByRole('alert')).toHaveText('Unable to load facilities.')
  await page.evaluate(() => window.renderFacilitiesFixture('empty', []))
  await expect(host.getByRole('group', { name: 'Facility status filters' }).getByRole('button')).toHaveText(['All0', 'Active0', 'Trial0', 'Past due0'])
  await page.evaluate(() => window.renderFacilitiesFixture('ready', [{ id: 'unknown-metrics', name: 'Isolated test hospital' }]))
  const cells = host.locator('tbody tr td')
  for (const index of [3, 4, 5]) await expect(cells.nth(index)).toHaveText('—')
  await host.getByRole('button', { name: 'View Isolated test hospital' }).click()
  await expect(page.getByRole('dialog').getByRole('group', { name: 'Facility summary' }).getByText('—', { exact: true })).toHaveCount(3)
  await page.keyboard.press('Escape')
})


test('missing facility details safely render no dialog', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/super-admin/preview/facilities')
  await page.evaluate(async () => {
    const [{ default: React }, { default: ReactDOM }, { default: Modal }] = await Promise.all([import('/node_modules/.vite/deps/react.js'), import('/node_modules/.vite/deps/react-dom_client.js'), import('/src/super-admin/FacilityDetailsModal.jsx')])
    const node = document.createElement('div'); document.body.append(node)
    ReactDOM.createRoot(node).render(React.createElement(Modal, { facility: null, onClose: () => {} }))
  })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('No facilities available yet.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
