import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 375, height: 667 }, { width: 390, height: 844 }, { width: 414, height: 896 }, { width: 430, height: 932 }, { width: 1024, height: 768 }, { width: 1280, height: 720 }, { width: 1366, height: 768 }, { width: 1440, height: 900 }]) {
  test(`System Health unavailable summaries, status and navigation at ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.route('**/api/**', route => { requests.push(route.request().url()); return route.abort() })
    await page.goto('/super-admin/preview/overview')
    const nav = page.getByRole('navigation', { name: 'Super Admin navigation' })
    await nav.getByRole('link', { name: 'System Health', exact: true }).click()
    await expect(page).toHaveURL(/\/super-admin\/preview\/system-health$/)
    await expect(nav.getByRole('link', { name: 'System Health', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('heading', { name: 'System Health', exact: true })).toBeVisible()
    await expect(page.getByText('Live status of MedTrail and the services it depends on. Checked every minute.', { exact: true })).toBeVisible()
    await expect(page.locator('[data-super-admin-layout] > section > p[role="status"]')).toContainText('no active login, monitoring data or automatic checks')
    await expect(page.getByRole('button', { name: 'Run checks now', exact: true })).toBeDisabled()
    const status = page.locator('[data-system-health-status]')
    await expect(status).toHaveAttribute('role', 'status')
    await expect(status).toHaveText('System health status is not available yet.')
    await expect(status).toHaveCSS('background-color', 'rgb(255, 244, 229)')
    await expect(status).toHaveCSS('font-size', '12px')
    const cards = page.getByRole('region', { name: 'System Health summary', exact: true })
    await expect(cards.getByRole('article')).toHaveCount(4)
    for (const label of ['API uptime - 30 days', 'API response time', 'Payment webhooks', 'Open incidents']) {
      const card = cards.getByRole('article', { name: label, exact: true })
      await expect(card.locator('p').first()).toHaveText('—')
      const support = card.locator('p').last()
      await expect(support).toHaveText('—')
      await expect(support).toHaveCSS('border-top-width', '1px')
      await expect(support).toHaveCSS('color', 'rgb(122, 129, 144)')
    }
    const boxes = await Promise.all((await cards.getByRole('article').all()).map(card => card.boundingBox()))
    expect(Math.max(...boxes.map(box => box.height)) - Math.min(...boxes.map(box => box.height))).toBeLessThan(1)
    if (viewport.width >= 1024) expect(boxes.map(box => box.y)).toEqual([boxes[0].y, boxes[0].y, boxes[0].y, boxes[0].y])
    const content = page.getByRole('region', { name: 'System Health content', exact: true })
    if (viewport.width >= 1024) expect(await content.evaluate(node => node.scrollHeight <= node.clientHeight)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(content.getByRole('table')).toHaveCount(1)
    await expect(content.getByText('No monitoring data available yet.', { exact: true })).toBeVisible()
    await expect(content.getByText('No incident data available yet.', { exact: true })).toBeVisible()
    await expect(content.getByRole('alert')).toHaveCount(0)
    await expect(content.getByText(/99\.98|182 ms|99\.8%|SMS Delays|October 2026|Investigating|service degraded|systems operational/i)).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`system-health-${viewport.width}.png`), fullPage: true })
    await nav.getByRole('link', { name: 'Messaging', exact: true }).click()
    await expect(page.getByText('No messages available yet.', { exact: true })).toBeVisible()
    await nav.getByRole('link', { name: 'Overview', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Platform overview', exact: true })).toBeVisible()
    expect(errors).toEqual([]); expect(requests).toEqual([])
  })
}

test('System Health never polls or simulates checks while open', async ({ page }) => {
  await page.clock.install({ time: new Date('2027-02-10T10:00:00Z') })
  const requests = []
  page.on('request', request => { if (['fetch', 'xhr'].includes(request.resourceType())) requests.push(request.url()) })
  await page.goto('/super-admin/preview/system-health')
  const cards = page.getByRole('region', { name: 'System Health summary' })
  await expect(cards.getByText('—', { exact: true })).toHaveCount(8)
  const initial = await cards.innerText()
  await page.clock.fastForward(120000)
  await expect(page.getByRole('button', { name: 'Run checks now' })).toBeDisabled()
  expect(await cards.innerText()).toBe(initial)
  expect(requests).toEqual([])
})
